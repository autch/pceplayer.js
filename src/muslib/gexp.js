'use strict';

const expt = [
    32768,
    34716,
    36781,
    38968,
    41285,
    43740,
    46341,
    49097,
    52016,
    55109,
    58386,
    61858,
];
const expb = [
    1948,
    2064,
    2187,
    2317,
    2455,
    2601,
    2756,
    2919,
    3093,
    3277,
    3472,
    3678,
];
// n は音程を 1/256 半音単位で表した値。返り値は 2 ** (n / (12 * 256) - 5) 相当の整数。
//
// 元実装は a = n >> 8 で div12t1[a] (= a % 12) と div12t2[a] (= 桁合わせのシフト量) を
// 引いていたが、両テーブルとも 21 * 12 + 4 = 256 エントリしかなかったため、
//   - a >= 252 (n >= 64512): シフト量が 0 で飽和し、1 オクターブ低い値を返す
//   - a >= 256 (n >= 65536): テーブル範囲外を引いて NaN >> undefined、つまり 0 を返す
// という壊れ方をしていた。0 が返ると MDevice.Render() の freq が 0 になり、
// 以降そのチャンネルは次の NoteOn まで無音になる。
// 高音側で音程が狂う / 発音しなくなる原因なので、表引きをやめて算術で求める。
export default function gexp(n) {
    if (n < 0) return 0;

    const a = n >> 8;
    const b = a % 12;                   // div12t1[] 相当
    const s = 20 - ((a / 12) | 0);      // div12t2[] 相当。負なら左シフト
    const v = expt[b] + ((expb[b] * (n & 0xff)) >> 8);

    return s >= 0 ? v >> s : v * (2 ** -s);
}
